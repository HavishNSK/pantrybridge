import { test, expect } from '@playwright/test'

async function clearData(page: import('@playwright/test').Page) {
  await page.goto('/settings?nowebgl')
  await page.getByRole('button', { name: 'Clear all my data', exact: true }).click()
  await page.getByRole('button', { name: 'Yes, clear everything', exact: true }).click()
}

test('food-box review to constrained three dinners, confirmation, persistence and deletion', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await clearData(page)
  await page.goto('/scan?nowebgl')
  await page.getByRole('radio', { name: 'Food box', exact: true }).check()
  await page.getByRole('button', { name: /sample/i }).click()
  await expect(page.getByText('Demo mode: these are sample results.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Save.*pantry/i }).click()
  await expect(page.getByRole('heading', { name: /Saved 6 items/ })).toBeVisible()
  await page.goto('/planner?nowebgl#three-dinners')
  await page.getByRole('button', { name: 'Preview three dinners', exact: true }).click()
  await expect(page.getByRole('heading', { name: '0 of 3 dinners fit', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Pot + stovetop', exact: true }).check()
  await page.getByRole('checkbox', { name: 'I have safe water for cooking', exact: true }).check()
  await page.getByRole('button', { name: 'Preview three dinners', exact: true }).click()
  await expect(page.getByRole('heading', { name: '3 of 3 dinners fit', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/dinners-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Save these dinners', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Save these dinners?', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save dinners to my week', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('checkbox', { name: 'Pot + stovetop', exact: true })).toBeChecked()
  await expect(page.getByText('3 meals planned', { exact: false }).first()).toBeVisible()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('pantrybridge:v1')!).state)
  expect(stored.pantry).toHaveLength(6)
  expect(stored.pantry.every((item: { demo?: boolean }) => item.demo)).toBe(true)
  expect(Object.values(stored.plan).filter((day) => typeof day === 'object' && day !== null && 'dinner' in day && day.dinner)).toHaveLength(3)
  await page.getByLabel('Add something else', { exact: true }).fill('Dish soap')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: 'Clear week', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Clear week', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Got Dish soap', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Pot + stovetop', exact: true }).uncheck()
  await page.getByRole('button', { name: 'Preview three dinners', exact: true }).click()
  await expect(page.getByRole('heading', { name: '0 of 3 dinners fit', exact: true })).toBeVisible()
  await page.goto('/privacy?nowebgl')
  await expect(page.getByRole('heading', { name: 'Privacy & storage', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'General Legal', exact: true })).toBeVisible()
  await clearData(page)
  const cleared = await page.evaluate(() => JSON.parse(localStorage.getItem('pantrybridge:v1')!).state)
  expect(cleared.pantry).toEqual([])
  expect(cleared.cookingPreferences.safeWater).toBe(false)
  expect(errors).toEqual([])
})

test('receipt requires package correction and excludes household supplies on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await clearData(page)
  await page.goto('/scan?nowebgl')
  await page.getByRole('radio', { name: 'Grocery receipt', exact: true }).check()
  await page.getByRole('button', { name: /sample/i }).click()
  await expect(page.getByText(/PAPER TOWELS/)).toBeVisible()
  const pasta = page.getByRole('spinbutton', { name: /Amount of.*pasta/i })
  await expect(pasta).toHaveValue('')
  await page.getByRole('button', { name: /Save.*pantry/i }).click()
  await expect(pasta).toBeFocused()
  await page.screenshot({ path: 'test-results/receipt-review-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await pasta.fill('300')
  await page.getByRole('button', { name: /Save.*pantry/i }).click()
  await expect(page.getByRole('heading', { name: /Saved 6 items/ })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/receipt-mobile.png', fullPage: true })
})

test('simple flow keeps optional photos and empty weekly tools out of the way', async ({ page }) => {
  await clearData(page)
  await page.goto('/scan?nowebgl')
  await expect(page.getByRole('heading', { name: 'Add food', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Choose a photo', exact: true })).not.toBeVisible()
  await page.getByText('Add a photo reference (optional)', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Choose a photo', exact: true })).toBeVisible()
  await page.goto('/planner?nowebgl')
  await expect(page.getByRole('button', { name: 'Suggest my week', exact: true })).not.toBeVisible()
  const calendar = page.locator('details').filter({ has: page.getByText('Weekly calendar (optional)', { exact: true }) })
  await expect(calendar).not.toHaveAttribute('open', '')
  await page.getByText('Weekly calendar (optional)', { exact: true }).click()
  await expect(calendar).toHaveAttribute('open', '')
  await expect(page.getByRole('checkbox', { name: 'Pot + stovetop', exact: true })).toBeVisible()
})
